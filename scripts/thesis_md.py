def vrow(t):
    v = V[t]
    if v["rule"] == "between":
        val, rule = f"{ratio(v['value'])} ({ratio(v['lo'])} to {ratio(v['hi'])})", f"{v['low']}× to {v['high']}×"
    elif t == "T6":
        val, rule = bps(v["value"]), f"above {v['threshold']} bps"
    else:
        val = f"{pct(v['value'])} ({pct(v['lo'])} to {pct(v['hi'])})"
        rule = f"{v['rule']} {pct(v['threshold'], 0)}"
    note = f" (main: {v['main']}; replication: {v['repl']}; pooled: {v['pooled']})" if v.get("repl") else ""
    return f"| {t} | {v['claim']} | {rule} | {val} | **{v['verdict']}**{note} |"


def md_cell(tid, r):
    v = r.get(tid)
    if v is None or (tid == "T1" and r["name"] == "Whales removed"):
        return "n/a"
    f = ratio if tid == "T1" else (lambda x: pct(x, 0))
    verdict = (" **" + judge(TBY[tid], v)[0] + "**") if tid in TBY else ""
    chain = (" " + cn(r["T2_chain"])) if tid == "T2" else ""
    return f"{f(v[0])} ({f(v[1])} to {f(v[2])}){chain}{verdict}"


